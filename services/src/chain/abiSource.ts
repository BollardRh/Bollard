import { readFileSync } from "node:fs";

/** Contracts whose ABIs the services use, as [constant name, forge artifact path under contracts/out]. */
export const ABI_SOURCES = [
  ["ratingRegistryAbi", "RatingRegistry.sol/RatingRegistry.json"],
  ["attesterRegistryAbi", "AttesterRegistry.sol/AttesterRegistry.json"],
  ["feeRouterAbi", "FeeRouter.sol/FeeRouter.json"],
  ["arenaBountyAbi", "ArenaBounty.sol/ArenaBounty.json"],
  ["safeRatingGuardAbi", "SafeRatingGuard.sol/SafeRatingGuard.json"],
  ["identityRegistryAbi", "IExternal.sol/IIdentityRegistry8004.json"],
  ["erc20Abi", "Mocks.sol/MockERC20.json"],
] as const;

export const CONTRACTS_OUT = new URL("../../../contracts/out/", import.meta.url).pathname;

export function renderAbis(outDir = CONTRACTS_OUT): string {
  const parts = ABI_SOURCES.map(([name, file]) => {
    const abi = (JSON.parse(readFileSync(`${outDir}${file}`, "utf8")) as { abi: unknown }).abi;
    return `export const ${name} = ${JSON.stringify(abi)} as const;\n`;
  });
  return `// GENERATED by services/scripts/gen-abis.ts from contracts/out. Do not edit.\n\n${parts.join("\n")}`;
}
